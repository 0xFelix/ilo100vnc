// ScancodeToHID maps a QEMU "qnum" key code (PC set 1 make code, extended
// keys as 0x80|code) to a HID usage, or 0 if unknown.
func ScancodeToHID(code uint32) uint16 {
	if code < uint32(len(xtTable)) {
		return xtTable[code]
	}
	return 0
}

