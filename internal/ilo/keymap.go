package ilo

// The iLO takes USB HID usage ids from the Keyboard/Keypad page
// (PROTOCOL.md 5.1). RFB clients send either X11 keysyms (layout dependent,
// mapped here assuming a US layout) or, with the QEMU extended key event,
// PC scancodes (layout independent, preferred).

// KeysymToHID returns the HID usage for an X11 keysym, or 0 if unknown.
func KeysymToHID(keysym uint32) uint16 {
	switch {
	case keysym >= 'a' && keysym <= 'z':
		return uint16(0x04 + keysym - 'a')
	case keysym >= 'A' && keysym <= 'Z':
		return uint16(0x04 + keysym - 'A')
	case keysym >= '1' && keysym <= '9':
		return uint16(0x1E + keysym - '1')
	case keysym >= 0xFFBE && keysym <= 0xFFC9: // F1-F12
		return uint16(0x3A + keysym - 0xFFBE)
	case keysym >= 0xFFCA && keysym <= 0xFFD5: // F13-F24
		return uint16(0x68 + keysym - 0xFFCA)
	case keysym >= 0xFFB1 && keysym <= 0xFFB9: // KP_1-KP_9
		return uint16(0x59 + keysym - 0xFFB1)
	}
	return keysymTable[keysym]
}

